#!/bin/sh
# フックの起動役。作業ディレクトリをプロジェクトの根に戻してから、フックを動かす。
#
# フックは「今の作業ディレクトリ」で動く。会話の途中で cd すると、相対パスで登録したフックが見つからず、
# python3 が終了コード 2 を返す。2 はフックでは「止める」の意味なので、全部のツール呼び出しが止まり、
# cd で戻ることもできなくなる（子のセッションが開始 1 分で止まった）。
# 根は CLAUDE_PROJECT_DIR（セッションを始めた場所）。無ければ今の場所のまま動かす。
# 無いフックは何もせず 0 で終える（スキルを消したあとに残った登録で止まらないように）。
#
# 使い方: "${CLAUDE_PROJECT_DIR:-.}/.claude/hooks/run.sh" <根からのパス> [引数...]
cd "${CLAUDE_PROJECT_DIR:-.}" 2>/dev/null || exit 0
f="$1"
[ -n "$f" ] || exit 0
shift
[ -f "$f" ] || exit 0
case "$f" in
  *.py) exec python3 "$f" "$@" ;;
  *)    exec "$f" "$@" ;;
esac
