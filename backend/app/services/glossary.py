_INDEX: dict[str, Term] = {}
for _term in TERMS:
    _INDEX[_term.term.lower()] = _term
    for _alias in _term.also:
        _INDEX.setdefault(_alias.lower(), _term)


def find(word: str) -> Term | None:
    """その言葉の説明。別名でも引ける。"""
    return _INDEX.get((word or "").strip().lower())


def search(query: str) -> list[Term]:
    """語で探す。説明の中身にも当てる（言葉を知らない人は説明から探す）。"""
    needle = (query or "").strip().lower()
    if not needle:
        return list(TERMS)
    out = []
    for term in TERMS:
        haystack = " ".join([term.term, term.reading, term.plain, term.matters, *term.also]).lower()
        if needle in haystack:
            out.append(term)
    return out
