"""読む前に、文字の並びだけを整える。

現場から届くファイルは、どこを通ってきたかで見た目が変わる。Windows で
保存すれば行末に \\r が付き、メモ帳で保存すれば先頭に見えない印（BOM）が付く。
機器から吸い出す道具によっては、字下げが空白ではなくタブになる。

中身は同じなのに読めない、という落ち方をする。しかも落ち方が静かで、
「ホスト名が読めません」「アクセス VLAN が入っていません」と、
中身の問題であるかのように出てしまう。

ここで整えるのは、意味を持たない差だけにする。行の順番も、語の並びも変えない。
"""

from __future__ import annotations

#: メモ帳などが付ける、見えない先頭の印
_BOM = "﻿"


def clean(text: str) -> str:
    """行末と字下げの書き方だけを揃える。"""
    if text.startswith(_BOM):
        text = text[len(_BOM) :]
    # 途中に紛れた分も落とす。ファイルを繋いだときに真ん中へ入ることがある
    text = text.replace(_BOM, "")
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    # タブは空白1つとして扱う。字下げの深さは、どの読み手も見ていない
    # （見ているのは「字下げされているかどうか」だけ）
    return text.replace("\t", " ")
